class TestDeviceInstallUdevRulesCli:
    def test_udev_rules_print_to_stdout(self, runner: CliRunner, mem_env, tmp_path: Path) -> None:
        out = tmp_path / "rules.txt"
        # Use --output instead of --apply so we don't need sudo
        res = runner.invoke(
            app,
            [
                "device",
                "install-udev-rules",
                "--output",
                str(out),
            ],
        )
        assert res.exit_code == 0
        assert out.exists()
        content = out.read_text()
        assert "Auto-generated by HIVE" in content

    def test_udev_rules_apply_default_path_writes(self, runner: CliRunner, mem_env) -> None:
        # We can't actually write to /etc without sudo; we just verify
        # the command exists and prints an error.
        res = runner.invoke(app, ["device", "install-udev-rules", "--apply"])
        # Either exit 0 (in docker/root) or exit 1 with permission message
        assert res.exit_code in (0, 1)


