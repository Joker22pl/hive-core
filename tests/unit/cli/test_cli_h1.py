"""CLI tests for H1 device commands (scan, register, db-list, install-udev-rules).

Uses HIVE_DB_URL=sqlite:///:memory: so no real DB is touched.
"""

from __future__ import annotations

from pathlib import Path

import pytest
from typer.testing import CliRunner

from hive.cli.main import app


@pytest.fixture
def runner() -> CliRunner:
    return CliRunner()


@pytest.fixture
def mem_env(monkeypatch):
    """Use an in-memory SQLite DB for the CLI invocations."""
    monkeypatch.setenv("HIVE_DB_URL", "sqlite:///:memory:")


class TestDeviceScanCli:
    def test_scan_runs(self, runner: CliRunner, mem_env) -> None:
        res = runner.invoke(app, ["device", "scan", "--no-persist", "--no-usb", "--no-serial"])
        assert res.exit_code == 0
        assert "Scanned 0 device(s)" in res.stdout

    def test_scan_json_output(self, runner: CliRunner, mem_env) -> None:
        import json

        res = runner.invoke(
            app,
            ["device", "scan", "--no-persist", "--no-usb", "--no-serial", "--json"],
        )
        assert res.exit_code == 0
        data = json.loads(res.stdout)
        assert "scanned" in data
        assert "devices" in data


